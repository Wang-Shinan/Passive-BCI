export function pickWord(exclude: readonly string[], rng: () => number): string {
  const pool = WORD_BANK.filter((w) => !exclude.includes(w))
  const source = pool.length ? pool : WORD_BANK
  return source[Math.floor(rng() * source.length)]!
}
